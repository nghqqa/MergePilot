# ---------------------------------------------------------------------------
# W3C traceparent propagation (HTTP header format)
# ---------------------------------------------------------------------------
#
# Format: version-trace_id-parent_id-trace_flags
#   version:    2 hex chars (always "00")
#   trace_id:   32 hex chars (lowercase)
#   parent_id:  16 hex chars (lowercase)
#   trace_flags: 2 hex chars ("00" = not sampled, "01" = sampled)
#
# We map the MergePilot SpanContext to/from this format so that spans can
# propagate across HTTP boundaries (Gateway → MCP) and back.

TRACEPARENT_HEADER = "traceparent"


def to_traceparent(ctx: SpanContext, sampled: bool = True) -> str:
    """Serialize a SpanContext to a W3C traceparent header value."""
    flags = "01" if sampled else "00"
    return "00-%s-%s-%s" % (ctx.trace_id, ctx.span_id, flags)


def from_traceparent(value: str, run_id: str = "") -> Optional[SpanContext]:
    """Parse a W3C traceparent header into a SpanContext.

    Returns None if the value is malformed (fail-closed: do not propagate
    a broken context).
    """
    if not value or not isinstance(value, str):
        return None
    parts = value.strip().split("-")
    if len(parts) != 4:
        return None
    _ver, trace_id, span_id, _flags = parts
    if len(trace_id) != 32 or len(span_id) != 16:
        return None
    try:
        int(trace_id, 16)
        int(span_id, 16)
    except ValueError:
        return None
    return SpanContext(trace_id=trace_id, span_id=span_id, run_id=run_id)


def inject_headers(headers: dict, ctx: SpanContext = None,
                   run_id: str = ""):
    """Inject traceparent + mp.run_id into an HTTP headers dict.

    Modifies ``headers`` in place and returns it. If no context is given,
    uses the current thread-local context.
    """
    ctx = ctx or get_current_context()
    if ctx is None:
        return headers
    headers[TRACEPARENT_HEADER] = to_traceparent(ctx)
    if run_id or ctx.run_id:
        headers["X-MP-Run-Id"] = run_id or ctx.run_id
    return headers


def extract_context(headers: dict, run_id: str = "") -> Optional[SpanContext]:
    """Extract a SpanContext from HTTP headers (traceparent + X-MP-Run-Id).

    Returns None if no valid traceparent is found.
    """
    tp = None
    for k, v in headers.items():
        if k.lower() == TRACEPARENT_HEADER:
            tp = v
            break
    if tp is None:
        return None
    # run_id from X-MP-Run-Id header or fallback
    for k, v in headers.items():
        if k.lower() == "x-mp-run-id":
            run_id = run_id or v
            break
    return from_traceparent(tp, run_id=run_id)


# ---------------------------------------------------------------------------
# Matrix / task-text trace carrier (PoC)
# ---------------------------------------------------------------------------
#
# Async handoff across Matrix rooms cannot use HTTP headers, so the W3C
# traceparent rides inside the task message body as a single trailing line.
# Strictly validated on parse; anything malformed yields None (fail-closed):
# we never resume a broken context. The trailer contains only hex IDs and a
# run_id — no prompt/code/credential content ever travels in it.

_CARRIER_LINE = re.compile(
    r"\[MPTRACE\] v=1 tp=([0-9a-f]{2})-([0-9a-f]{32})-([0-9a-f]{16})-([0-9a-f]{2})"
    r" run=([A-Za-z0-9._\-]+)")


def append_task_carrier(task_text: str, ctx: SpanContext = None) -> str:
    """Append (or refresh) the trailing MPTRACE line for outgoing dispatches.

    Idempotent: any existing trailer line is stripped first. With no current
    context the text is returned unchanged.
    """
    ctx = ctx or get_current_context()
    if ctx is None:
        return task_text
    base = task_text.rstrip()
    base = base.split("\n[MPTRACE] ")[0].rstrip()
    flags = "01"
    return (base + "\n[MPTRACE] v=1 tp=00-%s-%s-%s run=%s\n"
            % (ctx.trace_id, ctx.span_id, flags, ctx.run_id))


def parse_task_carrier(task_text: str) -> Optional[SpanContext]:
    """Extract SpanContext from the last valid MPTRACE line, else None."""
    if not task_text or not isinstance(task_text, str):
        return None
    match = None
    for line in task_text.splitlines():
        m = _CARRIER_LINE.search(line.strip())
        if m:
            match = m
    if match is None:
        return None
    trace_id, span_id = match.group(2), match.group(3)
    return SpanContext(trace_id=trace_id, span_id=span_id,
                       run_id=match.group(5))


def make_link(ctx: SpanContext) -> dict:
    """Build one link record referencing a producer's SpanContext."""
    return {"trace_id": ctx.trace_id, "span_id": ctx.span_id}


