GENAI_PROMPT_CAPTURE_DEFAULT_OFF = True  # content capture forbidden this round


def build_genai_attrs(**kw) -> dict:
    """Filter+map caller attributes down to the frozen allowlist."""
    out = {}
    for k, v in kw.items():
        mapped = GENAI_ATTR_ALLOWLIST.get(k)
        if mapped is not None and v is not None:
            out[mapped] = v
    return out


@contextlib.contextmanager
def entry_span(name: str, run_id: str, attrs: dict = None):
    """Root 'Entry' span for one MergePilot business run (e.g. pr_review)."""
    clean = build_genai_attrs(**(attrs or {}))
    with start_span(name, run_id=run_id, agent_role="manager", **clean) as sp:
        yield sp


class AgentWindowSpan:
    """Manually-opened Agent/Stage window span (dispatch → completion).

    Spans a controller observation window across events, so it cannot use a
    with-block. Holds the thread-local context while open so same-process
    children still attach correctly; restores the previous context on close.
    """

    def __init__(self, name: str, run_id: str, trace_id: str,
                 agent_role: str = "", stage: str = "", attempt: int = 0,
                 attrs: dict = None):
        self._prev = get_current_context()
        clean_attrs = build_genai_attrs(**(attrs or {}))
        self.span = SpanRecord(
            trace_id=trace_id or (self._prev.trace_id if self._prev else _gen_trace_id()),
            span_id=_gen_span_id(),
            parent_span_id=self._prev.span_id if self._prev else None,
            name=name,
            run_id=run_id,
        )
        if run_id:
            self.span.set_attribute("mp.run_id", run_id)
        if agent_role:
            self.span.set_attribute("mp.agent_role", agent_role)
        if stage:
            self.span.set_attribute("mp.stage", stage)
        self.span.set_attribute("mp.attempt", attempt)
        for k, v in clean_attrs.items():
            self.span.set_attribute(k, v)
        self.ctx = SpanContext(self.span.trace_id, self.span.span_id, run_id)
        _set_current_context(self.ctx)

    def finish(self, final_decision: str = "", verification_status: str = "",
               human_intervention: bool = False) -> None:
        for k, v in (("final_decision", final_decision),
                     ("verification_status", verification_status),
                     ("human_intervention", human_intervention)):
            mapped = GENAI_ATTR_ALLOWLIST.get(k)
            if mapped is not None:
                self.span.set_attribute(mapped, v)
        self._close("OK")

    def fail(self) -> None:
        self._close("ERROR")

    def _close(self, status: str) -> None:
        try:
            self.span.set_status(status)
        finally:
            self.span.end()
            if getattr(self.span, "drop_reason", None) == "redaction_failed":
                bump_export_stat("dropped_redaction")
            elif _global_collector is not None:
                try:
                    _global_collector.add_span(self.span)
                except Exception:
                    pass
            _set_current_context(self._prev)





# ---------------------------------------------------------------------------
# OTLP/HTTP protobuf encoding (AgentLoop ingestion is http/protobuf ONLY;
# official docs: "仅支持 HTTP/Protobuf，暂不支持 HTTP/JSON 和 gRPC").
# Hand-rolled minimal writer for the subset this codebase emits — no external
# dependency. Wire format reference: opentelemetry/proto/trace/v1.
# ---------------------------------------------------------------------------

def _pb_varint(n: int) -> bytes:
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        out.append(b | (0x80 if n else 0))
        if not n:
            return bytes(out)


def _pb_tag(field: int, wire: int) -> bytes:
    return _pb_varint((field << 3) | wire)


def _pb_len(field: int, payload: bytes) -> bytes:
    return _pb_tag(field, 2) + _pb_varint(len(payload)) + payload


def _pb_uint64_fixed(field: int, n: int) -> bytes:
    import struct
    return _pb_tag(field, 1) + struct.pack("<Q", n)


def _pb_kv(k: str, v: Any) -> bytes:
    # KeyValue{1: key, 2: AnyValue{1: string_value}}
    return _pb_len(1, k.encode()) + _pb_len(2, _pb_len(1, str(v).encode()))


_STATUS_CODE = {"OK": 1, "ERROR": 2}          # else UNSET=0
_SPAN_KIND_INTERNAL = 1                        # enum SpanKind


def span_to_otlp_proto(span: SpanRecord, service_name: str,
                       resource_attrs: dict = None) -> bytes:
    """Encode one SpanRecord as ExportTraceServiceRequest bytes."""
    # SDK identity defaults (honest: our own emitter, not LoongSuite probe);
    # OTEL_RESOURCE_ATTRIBUTES values take precedence over defaults.
    merged = {
        "telemetry.sdk.name": "mergepilot-otel",
        "telemetry.sdk.language": "python",
        "telemetry.sdk.version": "1",
    }
    merged.update(resource_attrs or {})
    kvs = [_pb_kv("service.name", service_name)]
    for k, v in merged.items():
        kvs.append(_pb_kv(k, v))
    resource = b"".join(_pb_len(1, x) for x in kvs)

    scope = _pb_len(1, b"mergepilot-otel") + _pb_len(2, b"1")
    t0 = int(span.start_time * 1e9)
    t1 = int((span.end_time or time.time()) * 1e9)
    parts = [
        _pb_len(1, bytes.fromhex(span.trace_id)),
        _pb_len(2, bytes.fromhex(span.span_id)),
    ]
    if span.parent_span_id:
        parts.append(_pb_len(4, bytes.fromhex(span.parent_span_id)))
    parts.append(_pb_len(5, span.name.encode()))
    parts.append(_pb_tag(6, 0) + _pb_varint(_SPAN_KIND_INTERNAL))
    parts.append(_pb_uint64_fixed(7, t0))
    parts.append(_pb_uint64_fixed(8, t1))
    for k, v in span.attributes.items():
        parts.append(_pb_len(9, _pb_kv(k, v)))
    for link in getattr(span, "links", []) or []:
        lm = _pb_len(1, bytes.fromhex(link["trace_id"])) + \
            _pb_len(2, bytes.fromhex(link["span_id"]))
        parts.append(_pb_len(11, lm))
    code = _STATUS_CODE.get(span.status, 0)
    parts.append(_pb_len(15, _pb_tag(3, 0) + _pb_varint(code)))
    span_msg = b"".join(parts)

    scope_spans = _pb_len(1, scope) + _pb_len(2, span_msg)
    resource_spans = _pb_len(1, resource) + _pb_len(2, scope_spans)
    return _pb_len(1, resource_spans)


def parse_resource_attributes(environ=None) -> dict:
    """Official OTEL_RESOURCE_ATTRIBUTES (k1=v1,k2=v2, URL-decoded)."""
    from urllib.parse import unquote
    raw = (environ if environ is not None else os.environ) \
        .get("OTEL_RESOURCE_ATTRIBUTES", "")
    out = {}
    for pair in raw.split(","):
        pair = pair.strip()
        if not pair or "=" not in pair:
            continue
        k, _, v = pair.partition("=")
        if k.strip():
            try:
                out[k.strip()] = unquote(v.strip())
            except Exception:
                out[k.strip()] = v.strip()
    return out


class OTLPExporter:
    """Sends completed spans to an OTLP/HTTP receiver.

    Fail-closed: if the receiver is unreachable, the export is silently
    dropped (logged to stderr). Business logic is never blocked by export
    failures.
    """

    def __init__(self, endpoint: str = "http://localhost:4318/v1/traces",
                 timeout: float = 2.0, headers: dict = None,
                 fmt: str = "json"):
        self.endpoint = endpoint
        self.timeout = timeout
        # AgentLoop ingestion is http/protobuf only; json kept for local
        # otelcol receivers and backward compatibility.
        self._format = fmt if fmt in ("json", "proto") else "json"
        # Auth/license headers ride on every export POST; their VALUES are
        # never logged, counted into stats, or exposed via repr/str paths.
        self._headers = dict(headers or {})
        self._failed = 0
        self._sent = 0
        # Telemetry must never be hijacked by ambient system proxies and must
        # not pay opener-construction cost per span.
        import urllib.request as _rq
        self._opener = _rq.build_opener(_rq.ProxyHandler({}))

    @staticmethod
    def headers_from_standard_env(environ=None) -> dict:
        """Parse OTEL_EXPORTER_OTLP_HEADERS (official OTel spec name).

        Format: ``key1=value1,key2=value2`` (URL-decoded per spec). Returns {}
        when unset/malformed-pair-wise — malformed pairs are skipped, keys are
        not invented by this codebase.
        """
        from urllib.parse import unquote
        raw = (environ if environ is not None else os.environ) \
            .get("OTEL_EXPORTER_OTLP_HEADERS", "")
        out = {}
        for pair in raw.split(","):
            pair = pair.strip()
            if not pair or "=" not in pair:
                continue
            k, _, v = pair.partition("=")
            k, v = k.strip(), v.strip()
            if k:
                try:
                    out[k] = unquote(v)
                except Exception:
                    out[k] = v
        return out

    def export(self, span: SpanRecord):
        """Export a single span. Non-blocking on failure."""
        import urllib.error
        # Official env (OTEL_SERVICE_NAME) wins over legacy MP_SERVICE_NAME.
        service_name = os.environ.get("OTEL_SERVICE_NAME") or \
            os.environ.get("MP_SERVICE_NAME", "mergepilot")
        if self._format == "proto":
            payload = span_to_otlp_proto(
                span, service_name,
                resource_attrs=parse_resource_attributes())
            content_type = "application/x-protobuf"
        else:
            content_type = "application/json"
            payload = json.dumps({
            "resourceSpans": [{
                "resource": {"attributes": [{
                    "key": "service.name",
                    "value": {"stringValue": service_name}
                }]},
                "scopeSpans": [{
                    "spans": [self._span_to_otlp(span)]
                }]
            }]
        }).encode("utf-8")
        try:
            from urllib.request import Request
            req_headers = dict(self._headers)
            req_headers["Content-Type"] = content_type
            req = Request(self.endpoint, data=payload,
                          headers=req_headers, method="POST")
            self._opener.open(req, timeout=self.timeout)
            self._sent += 1
            bump_export_stat("sent")
        except Exception:
            self._failed += 1
            bump_export_stat("failed_export")

    def _span_to_otlp(self, span: SpanRecord):
        """Convert SpanRecord to OTLP JSON span format."""
        otlp = {
            "traceId": span.trace_id,
            "spanId": span.span_id,
            "parentSpanId": span.parent_span_id or "",
            "name": span.name,
            "kind": "SPAN_KIND_INTERNAL",
            "startTimeUnixNano": str(int(span.start_time * 1e9)),
            "endTimeUnixNano": str(int((span.end_time or time.time()) * 1e9)),
            "status": {
                "code": 1 if span.status == "OK" else (2 if span.status == "ERROR" else 0),
            },
            "attributes": [
                {"key": k, "value": {"stringValue": str(v)}}
                for k, v in span.attributes.items()
            ],
        }
        if getattr(span, "links", None):
            otlp["links"] = [
                {"traceId": l.get("trace_id", ""), "spanId": l.get("span_id", "")}
                for l in span.links
            ]
        return otlp


class DualCollector:
    """Sends spans to both InMemoryCollector (for tests) and OTLPExporter
    (for local otelcol). Fail-closed on exporter errors."""

    def __init__(self, memory: InMemoryCollector = None,
                 exporter: OTLPExporter = None):
        self.memory = memory or InMemoryCollector()
        self.exporter = exporter

    def add_span(self, span: SpanRecord):
        self.memory.add_span(span)
        drop = getattr(span, "drop_reason", None)
        if drop == "redaction_failed":
            # Redaction itself failed → span must not reach any external sink.
            bump_export_stat("dropped_redaction")
            return
        if self.exporter is None:
            return
        try:
            self.exporter.export(span)
        except Exception:
            bump_export_stat("dropped_export")  # fail-closed; counted locally
