import hashlib
import random
import re


def _gen_span_id() -> str:
    return hashlib.sha256(os.urandom(16)).hexdigest()[:16]


def _gen_trace_id() -> str:
    return hashlib.sha256(os.urandom(16)).hexdigest()[:32]


class SpanContext:
    """Carries trace_id, span_id, and run_id across the call chain."""
    __slots__ = ("trace_id", "span_id", "run_id")

    def __init__(self, trace_id, span_id, run_id):
        self.trace_id = trace_id
        self.span_id = span_id
        self.run_id = run_id

    def child(self):
        return SpanContext(self.trace_id, _gen_span_id(), self.run_id)


# Thread-local current span context
import threading
_current_ctx = threading.local()


def get_current_context() -> Optional[SpanContext]:
    return getattr(_current_ctx, "ctx", None)


def _set_current_context(ctx: Optional[SpanContext]):
    if ctx is None:
        if hasattr(_current_ctx, "ctx"):
            del _current_ctx.ctx
    else:
        _current_ctx.ctx = ctx


@contextlib.contextmanager
def start_span(name: str, run_id: str = "", trace_id: str = "",
               agent_role: str = "", parent_span_id: str = None,
               links=None, **attributes):
    """Start a new span as a child of the current context (or root).

    PoC additions:
      - ``parent_span_id``: reattach a hop-root span to a producer span id
        carried over an async/HTTP boundary when no thread-local parent
        exists (cross-process rejoin on the same trace).
      - ``links``: list of {"trace_id","span_id"} dicts expressing async
        handoff (Span Link semantics); never fakes parenting.

    The span is automatically ended on context exit. If redaction itself
    fails, the span is marked ``drop_reason`` and is NOT exported anywhere,
    but the failure is counted locally.
    """
    parent = get_current_context()

    if trace_id and parent is None:
        # Root span — use provided trace_id
        ctx = SpanContext(trace_id, _gen_span_id(), run_id)
    elif parent is not None:
        # Child span — inherit trace_id from parent
        ctx = parent.child()
        if run_id and not ctx.run_id:
            ctx.run_id = run_id
    else:
        # No parent, no trace_id — generate both
        ctx = SpanContext(_gen_trace_id(), _gen_span_id(), run_id)

    effective_parent = parent.span_id if parent is not None else parent_span_id
    span = SpanRecord(
        trace_id=ctx.trace_id,
        span_id=ctx.span_id,
        parent_span_id=effective_parent,
        name=name,
        run_id=ctx.run_id,
        links=links,
    )

    # Set required attributes
    if run_id:
        span.set_attribute("mp.run_id", run_id)
    if trace_id or ctx.trace_id:
        span.set_attribute("mp.trace_id", trace_id or ctx.trace_id)
    if agent_role:
        span.set_attribute("mp.agent_role", agent_role)

    # Set extra attributes
    for k, v in attributes.items():
        span.set_attribute(k, v)

    _set_current_context(ctx)
    try:
        yield span
        if span.status == "UNSET":
            span.set_status("OK")
    except Exception as exc:
        span.set_status("ERROR")
        span.add_event("exception", {
            "type": type(exc).__name__,
            "message": str(exc)[:200],
            # NEVER include traceback (may contain secrets in env dumps)
        })
        raise
    finally:
        span.end()
        if getattr(span, "drop_reason", None) == "redaction_failed":
            bump_export_stat("dropped_redaction")
        elif _global_collector is not None:
            try:
                _global_collector.add_span(span)
            except Exception:
                pass  # fail-closed: observability must not break pipeline
        _set_current_context(parent)


