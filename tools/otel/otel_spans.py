"""M6-A · OpenTelemetry instrumentation for MergePilot.

Provides span creation, context propagation, and redaction for the
Controller → Gateway → Skill → MCP vertical slice.

Design decisions:
- Uses the existing MergePilot correlation IDs (run_id, trace_id,
  correlation_id) as OTel span ATTRIBUTES — not replacing them.
- OTel trace_id/span_id are generated by the SDK; the MergePilot
  trace_id is carried as the ``mp.trace_id`` attribute for correlation
  with the existing DB audit schema.
- Sensitive fields (PATs, tokens, env secrets) are NEVER written to
  span attributes; a denylist is enforced.
- Fail-closed: if OTel export fails, the business logic continues
  (observability must not break the pipeline), but the error is logged
  to stderr and the span is dropped (not retried inline).
- No SLS backend — exports to a local in-memory collector for testing
  and to OTLP HTTP for production (configurable).

Span naming contract (frozen):
  controller.process_event    — wraps the top-level controller event loop
  gateway.call_tool           — wraps each Policy Gateway MCP call
  skill.<skill_name>          — wraps each Skill execution
  mcp.upstream                — wraps each upstream Docker/GitHub API call

Required attributes on ALL spans:
  mp.run_id          — the task run identifier
  mp.trace_id        — the MergePilot internal trace ID (NOT OTel trace_id)
  mp.agent_role      — reviewer | fixer | verifier | coordinator | manager

Conditional attributes (by span type):
  controller: mp.stage, mp.attempt, mp.event_type, mp.verdict
  gateway:    mp.correlation_id, mp.tool, mp.decision, mp.git_sha
  skill:      mp.skill_name, mp.skill_version, mp.request_id, mp.status
  mcp:        mp.correlation_id, mp.endpoint, mp.method, mp.status_code
"""
from __future__ import annotations

import contextlib
import json
import os
import sys
import time
import traceback
from typing import Any, Optional

# ---------------------------------------------------------------------------
# Sensitive-field denylist — NEVER write these to span attributes
# ---------------------------------------------------------------------------

SENSITIVE_KEY_PATTERNS = (
    "token", "secret", "password", "passwd", "pat", "api_key",
    "apikey", "credential", "private_key", "auth_token",
    "authorization", "cookie", "session",
)

SENSITIVE_VALUE_PATTERNS = (
    "ghp_", "ghs_", "gho_", "sk-", "AKIA", "xox",
    "BEGIN RSA PRIVATE", "BEGIN OPENSSH PRIVATE",
)


def _is_sensitive_key(key: str) -> bool:
    kl = key.lower()
    return any(p in kl for p in SENSITIVE_KEY_PATTERNS)


def _is_sensitive_value(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    return any(p in value for p in SENSITIVE_VALUE_PATTERNS)


def redact_attributes(attrs: dict) -> dict:
    """Return a copy of ``attrs`` with sensitive keys/values removed."""
    out = {}
    for k, v in attrs.items():
        if _is_sensitive_key(k):
            out[k] = "<redacted>"
        elif _is_sensitive_value(v):
            out[k] = "<redacted>"
        else:
            out[k] = v
    return out


