# In-memory span collector (for local testing without OTLP backend)
# ---------------------------------------------------------------------------


class SpanRecord:
    """A single recorded span (OTel-compatible shape)."""
    __slots__ = ("trace_id", "span_id", "parent_span_id", "name",
                 "status", "start_time", "end_time", "attributes",
                 "events", "run_id")

    def __init__(self, trace_id, span_id, parent_span_id, name,
                 run_id, attributes=None):
        self.trace_id = trace_id
        self.span_id = span_id
        self.parent_span_id = parent_span_id
        self.name = name
        self.status = "OK"
        self.start_time = time.time()
        self.end_time = None
        self.attributes = redact_attributes(attributes or {})
        self.events = []
        self.run_id = run_id

    def set_attribute(self, key, value):
        if _is_sensitive_key(key) or _is_sensitive_value(value):
            self.attributes[key] = "<redacted>"
        else:
            self.attributes[key] = value

    def add_event(self, name, attributes=None):
        self.events.append({
            "name": name,
            "timestamp": time.time(),
            "attributes": redact_attributes(attributes or {}),
        })

    def set_status(self, status):
        if status not in ("OK", "ERROR", "UNSET"):
            raise ValueError("span status must be OK/ERROR/UNSET")
        self.status = status

    def end(self):
        self.end_time = time.time()

    @property
    def duration_ms(self):
        if self.end_time:
            return round((self.end_time - self.start_time) * 1000, 2)
        return None

    def to_dict(self):
        return {
            "trace_id": self.trace_id,
            "span_id": self.span_id,
            "parent_span_id": self.parent_span_id,
            "name": self.name,
            "status": self.status,
            "start_time": self.start_time,
            "end_time": self.end_time,
            "duration_ms": self.duration_ms,
            "run_id": self.run_id,
            "attributes": dict(self.attributes),
            "events": list(self.events),
        }


class InMemoryCollector:
    """Collects spans in-process for testing. Thread-safe."""

    def __init__(self):
        self.spans = []
        self._lock = __import__("threading").Lock()

    def add_span(self, span: SpanRecord):
        with self._lock:
            self.spans.append(span)

    def clear(self):
        with self._lock:
            self.spans.clear()

    def get_by_run_id(self, run_id):
        with self._lock:
            return [s for s in self.spans if s.run_id == run_id]

    def get_by_name(self, name):
        with self._lock:
            return [s for s in self.spans if s.name == name]

    def to_json(self):
        with self._lock:
            return json.dumps([s.to_dict() for s in self.spans], indent=2)

    @property
    def count(self):
        with self._lock:
            return len(self.spans)


# ---------------------------------------------------------------------------
# Global collector (singleton) — set by tests; None = no collection
# ---------------------------------------------------------------------------

_global_collector: Optional[InMemoryCollector] = None


def set_collector(collector: Optional[InMemoryCollector]):
    global _global_collector
    _global_collector = collector


def get_collector() -> Optional[InMemoryCollector]:
    return _global_collector


